"""MAGE (Li et al., 2024): extra training data from 27 generators and 10 writing domains, plus an OOD test set.

Why: the v1 detectors were trained on HC3 only (ChatGPT answers to questions) and failed on other kinds
of AI writing. MAGE ("Machine-generated text detection in the wild", yaful/MAGE on Hugging Face,
Apache-2.0) covers stories, opinion essays, reviews, news, scientific writing and more, generated by 27
models (OpenAI GPT, LLaMA, OPT, T5/FLAN, BLOOM, GLM, ...).

What this module does
---------------------
* ``load_mage(split)`` reads ``train/valid/test/test_ood_set_gpt.csv`` and returns rows in the project's
  format. **MAGE labels 1 = human, 0 = machine; the project uses 0 = human, 1 = AI, so labels are flipped.**
* Every text goes through :func:`src.text_utils.normalize_text` and :func:`mage_prepare_text`, which
  removes two class-specific artefacts measured on MAGE: the Reddit CMV moderator footer (human only)
  and machine continuations cut off mid-sentence (18.5 % of AI vs 5 % of human texts end without
  sentence punctuation) - every text is trimmed to its last complete sentence.
  Fragments that still end mid-sentence after the trim are dropped (both classes).
* ``build_mage_splits`` draws balanced samples spread evenly over the 10 domains: 9,000 training,
  1,000 validation and 2,000 in-distribution test texts from MAGE's own splits, and the complete
  out-of-distribution set (unseen domains CNN, IMDB, PubMed, DialogSum; unseen generator GPT-4).
"""

from __future__ import annotations

import re
import shutil
import urllib.request
from pathlib import Path

import numpy as np
import pandas as pd

from src.config import (
    LABEL_AI,
    LABEL_HUMAN,
    MAGE_CACHED_DIR,
    MAGE_FILES,
    MAGE_N_TEST,
    MAGE_N_TRAIN,
    MAGE_N_VAL,
    MAGE_RAW_DIR,
    MAGE_URL,
    MIN_WORDS,
    SEED,
)
from src.text_utils import normalize_text, word_count

COLUMNS = ["id", "question_id", "source", "label", "text", "word_count"]
QUESTION_ID_OFFSET = {"train": 1_000_000, "valid": 2_000_000, "test": 3_000_000, "ood": 4_000_000}
CMV_FOOTER = re.compile(r"\s*Hello, users of CMV!.*?Happy CMVing!\s*", re.DOTALL)
SENTENCE_END = re.compile(r"[.!?][\"')\]]*(?=\s|$)")
END_OK = re.compile(r"[.!?][\"')\]]*\s*$")


def mage_prepare_text(text: str) -> str:
    """Remove the CMV footer and trim a text that stops mid-sentence to its last complete sentence.

    The trim is applied only when it keeps at least half of the text; otherwise the text is left as is
    (it is then a fragment either way and dropping more would distort length).
    """
    text = CMV_FOOTER.sub(" ", text).strip()
    if not text or END_OK.search(text):
        return text
    ends = list(SENTENCE_END.finditer(text))
    if ends and ends[-1].end() >= len(text) / 2:
        return text[: ends[-1].end()].strip()
    return text


def resolve_file(name: str, raw_dir: Path = MAGE_RAW_DIR, cached_dir: Path = MAGE_CACHED_DIR) -> Path:
    """MAGE file from ``data/raw/mage``, else the shared cache, else download it there."""
    for folder in (raw_dir, cached_dir):
        path = Path(folder) / name
        if path.is_file():
            return path
    raw_dir.mkdir(parents=True, exist_ok=True)
    target, partial = raw_dir / name, raw_dir / f"{name}.part"
    print(f"[mage] downloading {name} from {MAGE_URL} ...")
    with urllib.request.urlopen(f"{MAGE_URL}/{name}", timeout=120) as response, open(partial, "wb") as out:
        shutil.copyfileobj(response, out)
    partial.replace(target)
    return target


def load_mage(split: str) -> pd.DataFrame:
    """One MAGE file as project rows (labels flipped, text normalised and prepared, short texts dropped)."""
    frame = pd.read_csv(resolve_file(MAGE_FILES[split]), keep_default_na=False)
    src = frame["src"].astype(str)
    domain = src.str.split("_").str[0]
    generator = src.str.extract(r"machine_(?:continuation|topical|specified)_(.+)$")[0].fillna("human")
    generator = generator.where(~src.str.contains("_human"), "human")
    texts = [mage_prepare_text(normalize_text(str(t))) for t in frame["text"]]
    out = pd.DataFrame({
        "id": [f"mage-{split}-{i}" for i in range(len(frame))],
        "question_id": QUESTION_ID_OFFSET[split] + np.arange(len(frame)),
        "source": "mage:" + domain + ":" + generator,
        "label": np.where(frame["label"].astype(int) == 1, LABEL_HUMAN, LABEL_AI),
        "text": texts,
        "word_count": [word_count(t) for t in texts],
        "domain": domain,
    })
    # Fragments that still end mid-sentence after the trim (mostly cut-off machine continuations) are
    # dropped for both classes, so sentence-final punctuation cannot reveal the class.
    complete = np.array([bool(END_OK.search(t)) for t in out["text"]])
    out = out[(out["word_count"] >= MIN_WORDS) & complete]
    return out[~out["text"].duplicated(keep="first")].reset_index(drop=True)


def sample_by_domain(frame: pd.DataFrame, n: int, seed: int = SEED) -> pd.DataFrame:
    """Balanced sample of ``n`` rows: n/2 per class, spread evenly over the domains."""
    rng = np.random.default_rng(seed)
    domains = sorted(frame["domain"].unique())
    per_cell = max(1, n // (2 * len(domains)))
    parts = []
    for label in (LABEL_HUMAN, LABEL_AI):
        for dom in domains:
            cell = frame[(frame["label"] == label) & (frame["domain"] == dom)]
            take = min(per_cell, len(cell))
            parts.append(cell.iloc[rng.choice(len(cell), size=take, replace=False)])
    sample = pd.concat(parts)
    return sample.iloc[rng.permutation(len(sample))].reset_index(drop=True)


def build_mage_splits(seed: int = SEED, limit: int | None = None) -> dict[str, pd.DataFrame]:
    """MAGE samples for training/validation/in-distribution test, and the full OOD test set."""
    cap = (lambda n: n) if limit is None else (lambda n: min(n, limit))
    splits = {
        "train": sample_by_domain(load_mage("train"), cap(MAGE_N_TRAIN), seed),
        "val": sample_by_domain(load_mage("valid"), cap(MAGE_N_VAL), seed),
        "test": sample_by_domain(load_mage("test"), cap(MAGE_N_TEST), seed),
    }
    ood = load_mage("ood")
    splits["ood"] = ood if limit is None else sample_by_domain(ood, cap(len(ood)), seed)
    return splits


def ending_rates(frame: pd.DataFrame) -> dict[str, float]:
    """Share of texts per class that end without sentence punctuation (the truncation artefact)."""
    out = {}
    for label, name in ((LABEL_HUMAN, "human"), (LABEL_AI, "ai")):
        texts = frame.loc[frame["label"] == label, "text"]
        out[name] = round(float(np.mean([not END_OK.search(t) for t in texts])) if len(texts) else 0.0, 4)
    return out
